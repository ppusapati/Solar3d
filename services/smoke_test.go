// listDrawings lists drawings in a project
func listDrawings(t *testing.T, cfg *SmokeTestConfig, projectID string) []*Drawing {
	url := fmt.Sprintf("%s/api/v1/workspace/projects/%s/drawings?page_size=100", cfg.APIGatewayURL, projectID)
	httpReq, err := http.NewRequestWithContext(
		context.Background(),
		"GET",
		url,
		nil,
	)
	if err != nil {
		t.Fatalf("Failed to create list drawings request: %v", err)
	}

	client := &http.Client{Timeout: defaultTimeout}
	resp, err := client.Do(httpReq)
	if err != nil {
		t.Fatalf("Failed to list drawings: %v", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		bodyBytes, _ := io.ReadAll(resp.Body)
		t.Fatalf("List drawings failed with status %d: %s", resp.StatusCode, string(bodyBytes))
	}

	var result map[string]interface{}
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		t.Fatalf("Failed to decode list response: %v", err)
	}

	drawingsData := result["drawings"].([]interface{})
	var drawings []*Drawing
	for _, d := range drawingsData {
		dMap := d.(map[string]interface{})
		drawings = append(drawings, &Drawing{
			DrawingID:     dMap["drawing_id"].(string),
			ProjectID:     dMap["project_id"].(string),
			Name:          dMap["name"].(string),
			Status:        dMap["status"].(string),
			RevisionCount: int(dMap["revision_count"].(float64)),
			EntityCount:   int(dMap["entity_count"].(float64)),
		})
	}
	return drawings
}

